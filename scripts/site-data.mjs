// Writes projects/site/src/generated/site-data.ts from files the repository already keeps: the
// contributors in .all-contributorsrc, the package version and the changelog. The site imports it,
// so the contributors page and the version badge never drift from the repository.
// Usage: node scripts/site-data.mjs (run by `npm run build:site` and `npm run start:site`).
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

/** The all-contributors emoji key, for the types this project lists. */
const CONTRIBUTION_LABELS = {
  code: 'Code',
  doc: 'Documentation',
  design: 'Design',
  test: 'Tests',
  infra: 'Infrastructure',
  maintenance: 'Maintenance',
  bug: 'Bug reports',
  ideas: 'Ideas',
  review: 'Reviews',
  example: 'Examples',
  question: 'Answering questions',
  security: 'Security',
  translation: 'Translation',
  content: 'Content',
};

export function siteData(rc, corePackage, changelog) {
  const contributors = rc.contributors.map((person) => ({
    login: person.login,
    name: person.name || person.login,
    avatar: person.avatar_url,
    profile: person.profile || `https://github.com/${person.login}`,
    contributions: person.contributions.map((type) => CONTRIBUTION_LABELS[type] ?? type),
  }));
  // The package title line is the file's own heading; the site renders its own.
  const changelogBody = changelog.replace(/^# .*\n+/, '');
  return { version: corePackage.version, contributors, changelog: changelogBody };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const data = siteData(
    JSON.parse(readFileSync('.all-contributorsrc', 'utf8')),
    JSON.parse(readFileSync('projects/core/package.json', 'utf8')),
    readFileSync('projects/core/CHANGELOG.md', 'utf8'),
  );
  mkdirSync('projects/site/src/generated', { recursive: true });
  writeFileSync(
    'projects/site/src/generated/site-data.ts',
    `// Generated by scripts/site-data.mjs. Do not edit.\nexport const SITE_DATA = ${JSON.stringify(data, null, 2)} as const;\n`,
  );
  console.log(`site data: v${data.version}, ${String(data.contributors.length)} contributors`);
}
